package microbench.internal.reporting

/** A JSON string literal, which is also a valid Scala string literal. */
object JsonString:

  def quote(text: String): String = "\"" + text.flatMap {
    case '"'          => "\\\""
    case '\\'         => "\\\\"
    case '\n'         => "\\n"
    case '\r'         => "\\r"
    case '\t'         => "\\t"
    case c if c < ' ' => f"\\u${c.toInt}%04x"
    case c            => c.toString
  } + "\""
